def build():
    """Return a list of case dicts with the same fields as the generated benchmark."""
    rows = []
    for pid, ftype, head, scam, legit, tail, edit in PAIRS:
        assert ftype in FRAUD_TYPES
        for label, middle in (("fraud", scam), ("legit", legit)):
            text = "\n".join(head + middle + tail)
            rows.append(dict(id=f"contrast-{pid}-{label}", split="contrast", kind="fraud" if label == "fraud" else "near",
                             key=ftype, label=label, fraud_type=ftype if label == "fraud" else None, pair=pid,
                             edit=edit, text=text, truth_signals=[], generator="human-author"))
    return rows
